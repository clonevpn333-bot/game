# Builds photo-projection textures for the hand-modelled cars from reference photos.
# Paint pixels -> grey shading (alpha = paint mask, recoloured in-game); everything else kept as-is.
# Logos / lettering / plates are painted out. Output: src/vehicles/photoTex.js (data URIs).
import colorsys, base64, io, sys
from PIL import Image, ImageFilter, ImageDraw
import numpy as np
def build(path, paint_fn, wipes=(), darks=(), outline=None, hiband=None):
    im = Image.open(path).convert('RGB'); a = np.asarray(im).astype(np.float32) / 255
    r, g, b = a[..., 0], a[..., 1], a[..., 2]; mx = a.max(-1); mn = a.min(-1); v = mx; s = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1e-6), 0)
    h = np.zeros_like(mx); d = np.maximum(mx - mn, 1e-6)
    h = np.where(mx == r, ((g - b) / d) % 6, np.where(mx == g, (b - r) / d + 2, (r - g) / d + 4)) / 6
    mask = paint_fn(h, s, v).astype(np.float32)
    # reflection highlights sitting inside painted areas are paint too (fill bright, low-saturation holes)
    mi = Image.fromarray((mask * 255).astype(np.uint8)); closed = np.asarray(mi.filter(ImageFilter.MaxFilter(9)).filter(ImageFilter.MinFilter(9))) > 127
    mask = np.where(closed & (s < 0.45) & (v > 0.45), 1.0, mask).astype(np.float32)
    m = Image.fromarray((mask * 255).astype(np.uint8)).filter(ImageFilter.MedianFilter(3)); mask = np.asarray(m).astype(np.float32) / 255
    L = 0.2126 * r + 0.7152 * g + 0.0722 * b; med = np.median(L[mask > 0.5]) if (mask > 0.5).any() else 0.4
    shade = np.clip(L / med * 0.62, 0, 1)
    out = a.copy(); 
    for c in range(3): out[..., c] = np.where(mask > 0.5, shade, a[..., c])
    if hiband:  # bright reflections in a band (e.g. along the window line) are paint
        y0, y1 = hiband; band = np.zeros_like(mask, dtype=bool); band[y0:y1, :] = True
        hit = band & (v > 0.55) & (s < 0.5); mask = np.where(hit, 1.0, mask)
        for c in range(3): out[..., c] = np.where(hit, np.clip(L / med * 0.62, 0, 0.85), out[..., c])
    if outline:  # anything outside the car's outline is background -> plain paint
        om = Image.new('L', im.size, 0); ImageDraw.Draw(om).polygon(outline, fill=255); inside = np.asarray(om) > 127
        for c in range(3): out[..., c] = np.where(inside, out[..., c], 0.62)
        mask = np.where(inside, mask, 1.0)
    for (x0, y0, x1, y1) in wipes:  # logo on paint -> plain paint shading from the surrounding band
        band = shade[max(0, y0 - 4):y1 + 4, x0:x1]; fill = np.median(band)
        out[y0:y1, x0:x1, :] = fill; mask[y0:y1, x0:x1] = 1
    for (x0, y0, x1, y1, col) in darks:
        out[y0:y1, x0:x1, :] = np.array(col) / 255; mask[y0:y1, x0:x1] = 0
    rgb = Image.fromarray((out * 255).astype(np.uint8)); al = Image.fromarray((mask * 255).astype(np.uint8))
    jb = io.BytesIO(); rgb.save(jb, 'JPEG', quality=90); pb = io.BytesIO(); al.save(pb, 'PNG', optimize=True)
    return 'data:image/jpeg;base64,' + base64.b64encode(jb.getvalue()).decode(), 'data:image/png;base64,' + base64.b64encode(pb.getvalue()).decode()
red = lambda h, s, v: ((h < 0.08) | (h > 0.9)) & (s > 0.12) & (v > 0.15)
petrol = lambda h, s, v: (h > 0.38) & (h < 0.7) & (s > 0.04) & (v > 0.13) & (v < 0.85)
sky = lambda h, s, v: (h > 0.5) & (h < 0.6) & (s > 0.4) & (v > 0.35)
