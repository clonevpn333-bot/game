#!/usr/bin/env node
// Builds data/library.js (a classic <script>, so index.html also works from file://)
// from data/library.json + data/meta.json, after validating every entry.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const core = require('../js/core.js');
const root = new URL('../', import.meta.url);
const lib = JSON.parse(readFileSync(new URL('data/library.json', root), 'utf8'));
const meta = JSON.parse(readFileSync(new URL('data/meta.json', root), 'utf8'));
const problems = core.validateLibrary(lib.videos);
if (problems.length) { console.error('Library problems:\n  ' + problems.join('\n  ')); process.exit(1); }
lib.videos.sort((a, b) => a.date.localeCompare(b.date) || a.id.localeCompare(b.id));
writeFileSync(new URL('data/library.json', root), JSON.stringify(lib, null, 1) + '\n');
const data = { schema: lib.schema, builtAt: new Date().toISOString(), videos: lib.videos, ...meta };
writeFileSync(new URL('data/library.js', root), '/* GENERATED by scripts/build-library.mjs — edit data/library.json instead */\nwindow.REWIND_DATA = ' + JSON.stringify(data) + ';\n');
const by = lib.videos.reduce((m, v) => ((m[v.status] = (m[v.status] || 0) + 1), m), {});
console.log(`Built ${lib.videos.length} videos`, by);
