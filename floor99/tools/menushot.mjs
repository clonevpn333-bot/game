// Screenshot the main menu / lounge / panels: node tools/menushot.mjs <outDir>
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const out = process.argv[2] || 'shots';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message, e.stack.slice(0, 400)));
page.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text().slice(0, 300)); });
await page.goto(`http://localhost:${process.env.PORT || 8099}/`);
await page.waitForSelector('#bootBtn:not([disabled])', { timeout: 90000 });
await page.screenshot({ path: `${out}/m0-boot.png`, timeout: 120000 });
await page.click('#bootBtn');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/m1-menu.png`, timeout: 120000 });
await page.click('[data-act=floors]');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/m2-floors.png`, timeout: 120000 });
await page.click('#panelClose');
await page.click('[data-act=soundtrack]');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/m3-soundtrack.png`, timeout: 120000 });
await page.click('#panelClose');
await page.evaluate(() => { window.__floor99.save.data.progress.started = true; window.__floor99.showLounge('wardrobe'); });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/m4-lounge.png`, timeout: 120000 });
await page.evaluate(() => { window.__floor99.state = 'elevator'; window.__floor99.elevator.setRide(1, 4); window.__floor99.elevator.progress = 0.5; document.getElementById('lounge').classList.remove('active'); });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/m5-elevator.png`, timeout: 120000 });
await browser.close();
